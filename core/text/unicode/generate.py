"""Generate portable property ranges from the checked-in Unicode 18.0 data."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
out = """// Generated by unicode/generate.py from Unicode 18.0.0 data.
// Unicode data copyright 2026 Unicode, Inc.; Unicode License v3 (unicode/LICENSE.txt).
package com.circuitnext.rastrio.core.text

"""
for name, filename, filterprop in [
    ('grapheme', 'GraphemeBreakProperty.txt', None),
    ('indic', 'DerivedCoreProperties.txt', 'InCB'),
    ('emoji', 'emoji-data.txt', 'Extended_Pictographic'),
    ('line', 'LineBreak.txt', None),
    ('eastAsian', 'EastAsianWidth.txt', None),
    ('category', 'UnicodeData.txt', None),
]:
    ranges = []
    names = {'Cn' if name == 'category' else 'Other': 0}
    first = None
    for line in (root / 'unicode' / filename).read_text().splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        fields = [s.strip() for s in line.split(';')]
        if filterprop and fields[1] != filterprop:
            continue
        prop = fields[2] if name in ('indic', 'category') else fields[1]
        if prop not in names:
            names[prop] = len(names)
        limits = fields[0].split('..')
        lo, hi = int(limits[0], 16), int(limits[-1], 16)
        if name == 'category':
            if fields[1].endswith(', First>'):
                first = lo
                continue
            if fields[1].endswith(', Last>'):
                lo = first
                first = None
        ranges.append((lo, hi, names[prop]))
    ranges.sort()
    # Merge neighboring equal values to bound generated bytecode and source size.
    merged = []
    for lo, hi, value in ranges:
        if merged and merged[-1][1] + 1 == lo and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], hi, value)
        else:
            merged.append((lo, hi, value))
    ranges = merged
    out += 'private val ' + name + 'Ranges = ' + ' + '.join(name + str(i) + '()' for i in range((len(ranges) + 399) // 400)) + '\n'
    for chunk in range(0, len(ranges), 400):
        out += 'private fun ' + name + str(chunk // 400) + '() = intArrayOf(\n'
        for i in range(chunk, min(chunk + 400, len(ranges)), 8):
            out += '    ' + ', '.join(str(v) for r in ranges[i:min(i + 8, chunk + 400)] for v in r) + ',\n'
        out += ')\n'
    out += 'internal fun ' + name + '(code: Int): Int = unicodeLookup(' + name + 'Ranges, code)\n'
    for prop, value in names.items():
        out += 'internal const val ' + name.upper() + '_' + prop.upper() + ' = ' + str(value) + '\n'
    out += '\n'
out += '''private fun unicodeLookup(ranges: IntArray, code: Int): Int {
    var low = 0
    var high = ranges.size / 3 - 1
    while (low <= high) {
        val middle = (low + high) ushr 1
        val offset = middle * 3
        when {
            code < ranges[offset] -> high = middle - 1
            code > ranges[offset + 1] -> low = middle + 1
            else -> return ranges[offset + 2]
        }
    }
    return 0
}
'''
(root / 'src/commonMain/kotlin/com/circuitnext/rastrio/core/text/UnicodeTables.kt').write_text(out)
