"""Convert approved SVGs to Android resources. Requires ImageMagick; no network I/O.

Run from any directory; --check compares packaged resources without writing them.
Generated resources deliberately have no project source header.
"""
import argparse
import subprocess
import tempfile
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "androidApp/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"
ANDROID = "http://schemas.android.com/apk/res/android"


def generate(destination):
    master = ET.parse(ROOT / "assets/brand/logo/rastrio-symbol.svg").getroot().find(SVG + "path")
    foreground = ET.parse(ROOT / "assets/brand/app/adaptive-foreground.svg").getroot().find(SVG + "path")
    background = ET.parse(ROOT / "assets/brand/app/adaptive-background.svg").getroot().find(SVG + "rect")
    assert foreground.get("d") == master.get("d"), "Adaptive asset must retain canonical geometry"
    assert foreground.get("transform") == "translate(18 18) scale(3)"
    assert foreground.get("fill") == "#FFFDF7" and background.get("fill") == "#315C73"
    generated = []

    def write(relative, content):
        path = destination / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        # Preserve existing notices on formerly hand-maintained resources.
        retained = {"drawable/ic_launcher_background.xml", "mipmap-anydpi-v26/ic_launcher.xml", "mipmap-anydpi-v26/ic_launcher_round.xml"}
        prefix = (ROOT / "androidApp/src/main/AndroidManifest.xml").read_text().split("<manifest", 1)[0] if relative in retained else '<?xml version="1.0" encoding="utf-8"?>\n'
        path.write_text(prefix + '<!-- Generated by scripts/generate_android_branding.py; edit canonical SVGs. -->\n' + content + "\n")
        generated.append(relative)

    for name, color in (("foreground", foreground.get("fill")), ("monochrome", "#FFFFFF")):
        write(f"drawable-v24/ic_launcher_{name}.xml", f'<vector xmlns:android="{ANDROID}" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n    <group android:translateX="18" android:translateY="18" android:scaleX="3" android:scaleY="3">\n        <path android:fillColor="{color}" android:pathData="{master.get("d")}" />\n    </group>\n</vector>')
    write("drawable/ic_launcher_background.xml", f'<shape xmlns:android="{ANDROID}" android:shape="rectangle"><solid android:color="{background.get("fill")}" /></shape>')
    for version in (26, 33):
        for name in ("ic_launcher", "ic_launcher_round"):
            mono = '\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />' if version == 33 else ""
            write(f"mipmap-anydpi-v{version}/{name}.xml", f'<adaptive-icon xmlns:android="{ANDROID}">\n    <background android:drawable="@drawable/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />{mono}\n</adaptive-icon>')
    # The entire approved 108-unit composition is scaled, without redrawing the mark.
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108"><rect width="108" height="108" fill="{background.get("fill")}"/><path fill="{foreground.get("fill")}" transform="{foreground.get("transform")}" d="{master.get("d")}"/></svg>'
    with tempfile.TemporaryDirectory() as temporary:
        source = Path(temporary) / "launcher.svg"
        source.write_text(svg)
        for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
            for name in ("ic_launcher", "ic_launcher_round"):
                relative = f"mipmap-{density}/{name}.png"
                output = destination / relative
                output.parent.mkdir(parents=True, exist_ok=True)
                args = ["magick", "-background", "none", "-density", "384", str(source), "-resize", f"{size}x{size}"]
                if name.endswith("round"):
                    radius = size / 2
                    args += ["(", "+clone", "-fill", "black", "-colorize", "100", "-fill", "white", "-draw", f"circle {radius},{radius} {radius},0", ")", "-alpha", "off", "-compose", "CopyOpacity", "-composite"]
                subprocess.run(args + ["-strip", "PNG32:" + str(output)], check=True)
                generated.append(relative)
    return generated


def startup_assets():
    """Derive startup-only artwork; launcher masters and their colors stay intact."""
    source = ET.parse(ROOT / "assets/brand/logo/rastrio-symbol.svg").getroot()
    master = source.find(SVG + "path").get("d")
    prefix = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from canonical SVGs by scripts/generate_android_branding.py. -->\n'
    vector = f'<vector xmlns:android="{ANDROID}" android:width="96dp" android:height="96dp" android:viewportWidth="24" android:viewportHeight="24"><path android:fillColor="#252622" android:pathData="{master}" /></vector>\n'
    result = {"shared/src/commonMain/composeResources/drawable/rastrio_symbol.xml": prefix + vector}
    # currentColor lets the static browser loader follow the same light/dark tokens.
    for path in source.iter(SVG + "path"):
        path.set("fill", "currentColor")
    ET.register_namespace("", "http://www.w3.org/2000/svg")
    result["webApp/src/webMain/resources/rastrio-symbol.svg"] = ET.tostring(source, encoding="unicode") + "\n"
    for qualifier, color in (("drawable", "#B8442E"), ("drawable-night", "#F2A08C")):
        result[f"androidApp/src/main/res/{qualifier}/ic_splash.xml"] = prefix + f'<vector xmlns:android="{ANDROID}" android:width="288dp" android:height="288dp" android:viewportWidth="108" android:viewportHeight="108"><group android:translateX="18" android:translateY="18" android:scaleX="3" android:scaleY="3"><path android:fillColor="{color}" android:pathData="{master}" /></group></vector>\n'
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary)
            generated = generate(output)
            stale = [name for name in generated if not (RES / name).exists() or (RES / name).read_bytes() != (output / name).read_bytes()]
            if stale:
                raise SystemExit("Stale Android branding resources: " + ", ".join(stale))
        stale = [name for name, content in startup_assets().items() if not (ROOT / name).exists() or (ROOT / name).read_text() != content]
        if stale:
            raise SystemExit("Stale startup branding resources: " + ", ".join(stale))
        print(f"Branding derivation PASS ({len(generated)} Android resources + {len(startup_assets())} startup assets)")
    else:
        print(f"Generated {len(generate(RES))} Android branding resources")
        for name, content in startup_assets().items():
            destination = ROOT / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content)
        print(f"Generated {len(startup_assets())} startup assets")
